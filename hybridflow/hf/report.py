def write_texts(m, res):
    """Data-driven sentences for the ablation and consistency paragraphs."""
    abl = [a for a in m.get("ablation", []) if a["set"] == "ablation" and a["model"].startswith("qwen")]
    ref = [a for a in m.get("ablation", []) if a["set"].startswith("ablation(")]
    by = {a["variant"]: a for a in abl}
    t = []
    if "P1" in by:
        a = by["P1"]
        t.append(f"The minimal prompt P1 produced free text from which no verdict could be extracted for "
                 f"{100 * a['parse_failure_rate']:.1f}\\% of the loops and reached an F1-score of {100 * a['f1']:.1f}\\% "
                 f"with {a['FP']} unsafe answer{'' if a['FP'] == 1 else 's'}, while consuming {a['tokens_per_loop']:.0f} tokens per loop.")
    parts = []
    for v in ("P2", "P3", "P4"):
        if v in by:
            a = by[v]
            parts.append(f"{v} {100 * a['f1']:.1f}\\% (FP {a['FP']}, {a['tokens_per_loop']:.0f} tokens per loop)")
    if parts:
        t.append("The structured prompts reached F1-scores of " + ", ".join(parts) + ".")
    if by:
        top = max(a["f1"] for a in by.values())
        bests = [v for v, a in sorted(by.items()) if abs(a["f1"] - top) < 1e-9]
        safe = [v for v, a in sorted(by.items()) if a["FP"] == 0]
        t.append(f"The highest F1-score was obtained with {' and '.join(bests)}; " +
                 ("no variant was free of unsafe answers." if not safe else
                  "variants without unsafe answers on this subset: " + ", ".join(safe) + "."))
    if ref:
        t.append("On the same loops, prompt P2 reached " + " and ".join(
            f"{100 * a['f1']:.1f}\\% with {a['model'].split('/')[-1].replace('gpt-oss', 'GPT-OSS').replace('b', 'B')}"
            for a in ref) + ". Because this subset contains no overlapping-call variants, all models score higher here than on the full evaluation set.")
