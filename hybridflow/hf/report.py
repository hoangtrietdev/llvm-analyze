MTAG = {"openai/gpt-oss-120b": "OneTwenty", "openai/gpt-oss-20b": "Twenty", "qwen/qwen3.8-27b": "Qwen"}


def _key_macro(key):
    for m, t in MTAG.items():
        for pre, name in (("pred_hf50_", "HFifty"), ("pred_hfc_", "HC"), ("pred_hf_", "H"), ("pred_hb_", "HB"), ("pred_ai_", "AI")):
            if key == pre + m:
                return name + t
    return {"pred_static": "Static", "pred_gcc": "Gcc", "pred_polly": "Polly"}.get(key)


