"""LaTeX tables (booktabs) and a Markdown report generated from metrics.json."""
import os

from .analysis_fmt import pct, num, esc


def _tab(name, res, caption, label, colspec, header, body, note=None):
    lines = ["% generated by hf/report.py from results/metrics.json - do not edit by hand",
             "\\begin{table}[htbp]", f"\\caption{{{caption}}}", f"\\label{{{label}}}", "\\centering",
             "\\small", "\\resizebox{\\linewidth}{!}{%" if len(header) > 6 else "",
             f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    lines += [" & ".join(str(c) for c in row) + " \\\\" for row in body]
    lines += ["\\bottomrule", "\\end{tabular}", "}" if len(header) > 6 else ""]
    if note:
        lines.append(f"\\par\\smallskip\\footnotesize {note}")
    lines.append("\\end{table}")
    os.makedirs(os.path.join(res, "tables"), exist_ok=True)
    with open(os.path.join(res, "tables", name + ".tex"), "w") as f:
        f.write("\n".join(l for l in lines if l != "") + "\n")


def write(m, res):
    b = m["benchmark"]
    # T1: benchmark composition
    body = [[esc(d["domain"].replace("_", " ")), d["files"], num(d["lines"]), d["bases"], d["loops"], d["parallel"], d["serial"]]
            for d in b["domain_table"]]
    body.append(["\\textbf{Total}", b["files"], num(b["physical_lines"]), b["base_kernels"], b["loops"],
                 b["gt_parallel"], b["gt_serial"]])
    _tab("bench", res, "Composition of HF-LoopBench (all numbers counted from the generated sources).",
         "tab:bench", "lrrrrrr", ["Domain", "Files", "Lines", "Base kernels", "Target loops", "GT par.", "GT ser."], body)

    # T2: oracle
    os_ = b["oracle_status"]
    body = [["GT-parallel loops verified (12 runs each)", os_.get("verified", 0)],
            ["GT-parallel loops violating their label", os_.get("VIOLATION", 0)],
            ["GT-serial loops whose naive parallelisation changed the output", os_.get("serial_manifested", 0)],
            ["GT-serial loops without an observed deviation", os_.get("serial_not_manifested", 0)],
            ["GT-serial loops not in OpenMP canonical form", os_.get("serial_noncanonical", 0)]]
    _tab("oracle", res, "Dynamic validation of the ground truth on the M1 Pro.", "tab:oracle", "lr",
         ["Outcome", "Loops"], body)

    # T3: full-set compilers
    body = []
    for name, s in m["full_set"].items():
        body.append([name, s["TP"], s["FP"], s["TN"], s["FN"], pct(s["precision"]), pct(s["recall"]),
                     f"{pct(s['f1'])} [{pct(s['f1_ci'][0])}, {pct(s['f1_ci'][1])}]", f"{s['mcc']:.3f}"])
    _tab("fullset", res, f"Compiler-based tools on all {b['usable']} target loops (95\\% cluster-bootstrap CI).",
         "tab:fullset", "lrrrrrrrr", ["Tool", "TP", "FP", "TN", "FN", "Prec.", "Rec.", "F1 [95\\% CI]", "MCC"], body)

    # T4: evaluation-set comparison
    body = []
    for e in m.get("eval_table", []):
        body.append([esc(e["method"]).replace("tau*", "$\\tau^*$").replace("tau=0.5", "$\\tau{=}0.5$"),
                     e["TP"], e["FP"], e["TN"], e["FN"], pct(e["precision"]), pct(e["recall"]),
                     f"{pct(e['f1'])} [{pct(e['f1_ci'][0])}, {pct(e['f1_ci'][1])}]", f"{e['mcc']:.3f}"])
    _tab("evalset", res, f"All methods on the LLM evaluation set ({m.get('eval_set_size', 0)} loops).",
         "tab:evalset", "lrrrrrrrr", ["Method", "TP", "FP", "TN", "FN", "Prec.", "Rec.", "F1 [95\\% CI]", "MCC"], body)

    # T5: threshold sweep for the primary model
    sw = m.get("sweeps", {})
    for model, rows in sw.items():
        body = [[f"{r['tau']:.2f}", r["ai"]["FP"], pct(r["ai"]["f1"]), r["hybrid_nofacts_ctx"]["FP"], pct(r["hybrid_nofacts_ctx"]["f1"]),
                 r["hybrid"]["FP"], pct(r["hybrid"]["f1"]),
                 r["hybrid_ctx"]["TP"], r["hybrid_ctx"]["FP"], pct(r["hybrid_ctx"]["f1"]), r["hybrid_ctx_dev"]["FP"]] for r in rows]
        tag = model.split("/")[-1].replace(".", "")
        _tab(f"sweep_{tag}", res, f"Sensitivity to the confidence threshold $\\tau$ ({esc(model)}).",
             f"tab:sweep-{tag}", "rrrrrrrrrrr",
             ["$\\tau$", "AI-only FP", "AI-only F1", "No facts FP", "No facts F1", "No guard FP", "No guard F1",
              "Full TP", "Full FP", "Full F1", "Full FP (dev)"], body,
             note="AI-only: P2 answers gated by $\\tau$. No facts: veto + call-site guard + P2 answers. No guard: veto + H answers. "
                  "Full: veto + call-site guard + H answers (complete system). F1 in \\%.")

    # T6: per-class breakdown
    if m.get("class_breakdown"):
        body = [[esc(r["group"]), r["gt"], r["n"], r["static_unknown"], pct(r["acc_static"]), pct(r["acc_gcc"]),
                 pct(r["acc_ai"]), pct(r["acc_hybrid"]), pct(r["acc_hybrid_ctx"])] for r in m["class_breakdown"]]
        _tab("classes", res, "Accuracy (\\%) per dependence class on the evaluation set (primary model).", "tab:classes",
             "lcrrrrrrr", ["Dependence class", "GT", "Loops", "Static UNK", "Static", "GCC", "AI-only", "Hybrid", "Hybrid+ctx"], body)

    # T7: cost
    body = []
    for c in m.get("cost", []):
        body.append([esc(c["model"].split("/")[-1]), c["variant"], esc(c["set"]), c["loops"], c["requests"],
                     num(c["prompt_tokens"]), num(c["completion_tokens"]), f"{c['tokens_per_loop']:.0f}",
                     f"{c['latency_per_request_s']:.2f}", "--" if c["usd"] is None else f"{c['usd']:.4f}"])
    _tab("cost", res, "Measured LLM usage (Groq API, token counts from the API responses).", "tab:cost",
         "llllrrrrrr", ["Model", "Prompt", "Set", "Loops", "Req.", "In tok.", "Out tok.", "Tok./loop", "s/req.", "USD"], body)

    # T8: ablation
    if m.get("ablation"):
        body = [[esc(a["model"].split("/")[-1]), a["variant"], esc(a["set"]), a["n"], pct(a.get("parse_failure_rate", 0)) if "parse_failure_rate" in a else "--",
                 a["FP"], pct(a["precision"]), pct(a["recall"]), pct(a["f1"]),
                 f"{a['tokens_per_loop']:.0f}" if "tokens_per_loop" in a else "--"] for a in m["ablation"]]
        _tab("ablation", res, "Prompt ablation (AI-only, no compiler facts).", "tab:ablation", "lllrrrrrrr",
             ["Model", "Prompt", "Set", "Loops", "Parse fail", "FP", "Prec.", "Rec.", "F1", "Tok./loop"], body)

    # T9: cache
    if m.get("cache"):
        body = [[f"{c['threshold']:.2f}", c["queried_loops"], c["hits"], pct(c["hit_rate"]), pct(c["accuracy_fresh"]),
                 pct(c["accuracy_cached"]), c["hits_changed_verdict"], c["fresh_fp"], c["cache_fp"]] for c in m["cache"]]
        _tab("cache", res, "Structural cache replayed over the recorded hybrid answers.", "tab:cache", "rrrrrrrrr",
             ["Sim.", "Queries", "Hits", "Hit rate", "Acc. fresh", "Acc. cached", "Changed", "FP fresh", "FP cached"], body)

    # unknown-reason table body (static analysis)
    rows_ = m["static"]["unknown_reasons"]
    with open(os.path.join(res, "tables", "unknown_reasons_body.tex"), "w") as f:
        f.write("% generated by hf/report.py\n\\begin{tabular}{lr}\n\\toprule\nReason reported by HF-Static & Loops \\\\\n\\midrule\n")
        for reason, n in rows_:
            f.write(f"{esc(reason)} & {n} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")

    # Markdown report
    md = ["# Hybrid-Flow v2 - measured results", "",
          "All numbers below are computed by `hf/analysis.py` from the files in `results/`.", ""]
    env = m.get("environment", {}).get("static") or {}
    md += ["## Environment", "", "```", *(f"{k}: {v}" for k, v in env.items()), "```", ""]
    md += ["## Benchmark", "", f"- files: {b['files']}, physical lines: {b['physical_lines']}, SLOC: {b['sloc']}",
           f"- base kernels: {b['base_kernels']}, target loops: {b['loops']} (parallel {b['gt_parallel']}, serial {b['gt_serial']}), domains: {b['domains']}",
           f"- oracle: {b['oracle_status']}", ""]
    md += ["## Compiler tools (all loops)", "", "| Tool | TP | FP | TN | FN | Prec | Rec | F1 | MCC |", "|---|---|---|---|---|---|---|---|---|"]
    for name, s in m["full_set"].items():
        md.append(f"| {name} | {s['TP']} | {s['FP']} | {s['TN']} | {s['FN']} | {pct(s['precision'])} | {pct(s['recall'])} | {pct(s['f1'])} | {s['mcc']:.3f} |")
    md += ["", "## Evaluation set", "", "| Method | TP | FP | TN | FN | Prec | Rec | F1 [CI] | MCC |", "|---|---|---|---|---|---|---|---|---|"]
    for e in m.get("eval_table", []):
        md.append(f"| {e['method']} | {e['TP']} | {e['FP']} | {e['TN']} | {e['FN']} | {pct(e['precision'])} | {pct(e['recall'])} | "
                  f"{pct(e['f1'])} [{pct(e['f1_ci'][0])}, {pct(e['f1_ci'][1])}] | {e['mcc']:.3f} |")
    md += ["", "## McNemar tests", ""] + [f"- {t['a']} vs {t['b']}: a-only correct {t['a_only_correct']}, b-only correct "
                                         f"{t['b_only_correct']}, p = {t['p_value']:.3g}" for t in m.get("mcnemar", [])]
    md += ["", "## Static analysis", "", f"- 3-way confusion: {m['static']['confusion3']}",
           f"- UNKNOWN reasons: {m['static']['unknown_reasons']}", f"- false PARALLEL: {m['static']['false_parallel']}", ""]
    for key in ("class_breakdown", "mode_breakdown", "ai_false_parallel", "hybrid_false_parallel", "veto_saves",
                "cost", "cost_projection", "ablation", "consistency", "cache", "perf", "field"):
        if key in m:
            md += [f"## {key}", "", "```", _pretty(m[key]), "```", ""]
    with open(os.path.join(res, "REPORT.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    write_numbers(m, res)
    write_texts(m, res)


def _pretty(x):
    import json
    return json.dumps(x, indent=1, default=str)[:20000]


