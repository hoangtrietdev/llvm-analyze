"""
Additional tables, figures and macros for the journal paper (paper/), computed
from results/ (main suite) and results/ext/ (HF-LoopBench-X).  Nothing here is
typed in by hand; run after `run_all.py analyze` and `hf.ext_analysis`.

Output: results/paper_extra/{numbers_extra.tex, tables/*.tex, fig_*.tex}
"""
import glob
import json
import math
import os
from collections import Counter

from .analysis import CACHED_INPUT, MODEL_SHORT, PRICES
from .common import read_json, read_jsonl

HDR = "% generated by hf/paper_extra.py - do not edit by hand\n"
TAG = {"openai/gpt-oss-20b": "Twenty", "openai/gpt-oss-120b": "OneTwenty", "qwen/qwen3.8-27b": "Qwen"}
DAILY_TOKENS = 200000


def pct(x, d=1):
    return f"{100 * x:.{d}f}"


def num(n):
    return f"{n:,}"


def table(path, caption, label, colspec, header, body, size="\\small", wide=False):
    L = [HDR, "\\begin{table}[htbp]", f"\\caption{{{caption}}}", f"\\label{{{label}}}", "\\centering", size]
    if wide:
        L.append("\\resizebox{\\linewidth}{!}{%")
    L += [f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", header + " \\\\", "\\midrule"]
    L += [r + " \\\\" if r not in ("\\midrule",) else r for r in body]
    L += ["\\bottomrule", "\\end{tabular}"]
    if wide:
        L.append("}")
    L.append("\\end{table}")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")


def run(root, log=print):
    res = os.path.join(root, "results")
    out = os.path.join(res, "paper_extra")
    os.makedirs(os.path.join(out, "tables"), exist_ok=True)
    m = read_json(os.path.join(res, "metrics.json"))
    mx = read_json(os.path.join(res, "ext", "metrics_ext.json"), {})
    N = {}

    # ---------------- 1. pipeline reduction on the 200-file corpus ----------------
    fm = read_json(os.path.join(res, "field_meta.json"))
    frows = read_jsonl(os.path.join(res, "field_static.jsonl"))
    v = Counter(r["verdict"] for r in frows)
    raw, proj = fm["all_loop_records"], fm["project_loops"]
    pass_s = sum(x.get("pass_s", 0) for x in fm["files"].values() if x.get("ok"))
    dom = Counter()
    domv = {}
    for r in frows:
        d = r["file"].split("real-world/")[-1].split("/")[0]
        dom[d] += 1
        domv.setdefault(d, Counter())[r["verdict"]] += 1
    N.update(plRaw=num(raw), plHeader=num(raw - proj), plDecided=num(v["PARALLEL"] + v["SERIAL"]),
             plDecidedPct=pct((v["PARALLEL"] + v["SERIAL"]) / proj) + "\\%", plPassSeconds=f"{pass_s:.1f}")
    body = [f"Phase 1: natural loops found (incl.\\ system/library headers) & {num(raw)} & ",
            f"Phase 1: loops in system/library headers removed & $-${num(raw - proj)} & ",
            f"Phase 1: project loops & {num(proj)} & 100.0\\%",
            "\\midrule",
            f"Phase 2: proven \\textsc{{Parallel}} (directive emitted, no model call) & {num(v['PARALLEL'])} & {pct(v['PARALLEL'] / proj)}\\%",
            f"Phase 2: proven \\textsc{{Serial}} (veto) & {num(v['SERIAL'])} & {pct(v['SERIAL'] / proj)}\\%",
            f"Phase 2: \\textsc{{Unknown}} $\\rightarrow$ candidates for Phases 3--4 & \\textbf{{{num(v['UNKNOWN'])}}} & \\textbf{{{pct(v['UNKNOWN'] / proj)}\\%}}"]
    table(os.path.join(out, "tables", "pipeline.tex"),
          f"Loops of the 200-file application corpus ({num(fm['total_lines'])} lines, 10 domains) through the deterministic phases.",
          "tab:pipeline", "lrr", "Pipeline phase & Loops & Share", body)
    ddom = [f"{d.replace('_', ' ')} & {n} & {domv[d]['PARALLEL']} & {domv[d]['SERIAL']} & {domv[d]['UNKNOWN']}"
            for d, n in sorted(dom.items())]
    table(os.path.join(out, "tables", "pipeline_domains.tex"),
          "HF-Static verdicts per domain of the application corpus.", "tab:pipeline-domains", "lrrrr",
          "Domain & Loops & \\textsc{Par} & \\textsc{Ser} & \\textsc{Unk}", ddom)

    # ---------------- 2. AI output distribution (P2, evaluation set) ----------------
    per = {r["function"]: r for r in read_json(os.path.join(res, "per_loop.json"))}
    bins = [(0.95, 1.01, "$c \\ge 0.95$"), (0.90, 0.95, "$0.90 \\le c < 0.95$"), (0.80, 0.90, "$0.80 \\le c < 0.90$"),
            (0.0, 0.80, "$c < 0.80$")]
    models = [x for x in ("openai/gpt-oss-20b", "openai/gpt-oss-120b") if os.path.exists(
        os.path.join(res, "ai", x.replace("/", "_") + "__P2__eval.json"))]
    preds = {mm: read_json(os.path.join(res, "ai", mm.replace("/", "_") + "__P2__eval.json"))["predictions"] for mm in models}
    body = []
    for lo, hi, lab in bins:
        cells = []
        for mm in models:
            P = [(f, p) for f, p in preds[mm].items() if f in per and p.get("verdict") and lo <= p.get("confidence", 0) < hi]
            par = [f for f, p in P if p["verdict"] == "parallel"]
            ser = [f for f, p in P if p["verdict"] != "parallel"]
            cells += [str(len(par)), str(sum(per[f]["gt"] == "S" for f in par)),
                      str(len(ser)), str(sum(per[f]["gt"] == "P" for f in ser))]
        body.append(lab + " & " + " & ".join(cells))
    cells = []
    for mm in models:
        unans = sum(1 for f in per if f in preds[mm] and not preds[mm][f].get("verdict"))
        cells += [str(unans), "", "", ""]
    body.append("no parsable answer & " + " & ".join(cells))
    hdr1 = " & " + " & ".join(f"\\multicolumn{{4}}{{c}}{{{MODEL_SHORT[mm]}}}" for mm in models)
    hdr2 = "Confidence & " + " & ".join(["``parallel'' & unsafe & ``serial'' & missed"] * len(models))
    table(os.path.join(out, "tables", "ai_dist.tex"),
          "Answers of the LLMs alone (prompt P2, evaluation set) by self-reported confidence $c$. "
          "Unsafe: ``parallel'' answers for loops whose GT is serial; missed: ``serial'' answers for GT-parallel loops.",
          "tab:aidist", "l" + "rrrr" * len(models), hdr1 + " \\\\ " + hdr2, body, wide=True)
    for mm in models:
        t = TAG[mm]
        hi_unsafe = sum(1 for f, p in preds[mm].items() if f in per and p.get("verdict") == "parallel"
                        and per[f]["gt"] == "S" and p.get("confidence", 0) >= 0.9)
        all_unsafe = sum(1 for f, p in preds[mm].items() if f in per and p.get("verdict") == "parallel" and per[f]["gt"] == "S")
        N[f"aiHiConfUnsafe{t}"] = hi_unsafe
        N[f"aiUnsafe{t}"] = all_unsafe

    # ---------------- 3. McNemar table ----------------
    nm = {"pred_static": "LLVM-only", "pred_gcc": "GCC"}
    for mm in models:
        s = MODEL_SHORT[mm]
        nm.update({f"pred_ai_{mm}": f"AI-only {s}", f"pred_hfc_{mm}": f"Hybrid {s}",
                   f"pred_hf_{mm}": f"Hybrid {s} w/o guard", f"pred_hb_{mm}": f"Hybrid {s} w/o facts"})
    body = []
    for t in m["mcnemar"]:
        if not (t["a"].startswith("pred_hfc_") and t["b"] in ("pred_static", "pred_gcc") or
                t["a"].startswith("pred_hfc_") and t["b"].startswith(("pred_ai_", "pred_hf_", "pred_hb_")) or
                t["a"].startswith("pred_ai_") and t["b"] == "pred_static"):
            continue
        p = t["p_value"]
        ps = "$<0.001$" if p < 0.001 else f"{p:.3f}"
        body.append(f"{nm.get(t['a'], t['a'])} vs.\\ {nm.get(t['b'], t['b'])} & {t['a_only_correct']} & {t['b_only_correct']} & {ps}")
    table(os.path.join(out, "tables", "mcnemar.tex"),
          f"Exact McNemar tests on per-loop correctness (evaluation set, {m['eval_set_size']} loops). "
          "$b$: loops only the first method gets right; $c$: loops only the second gets right.",
          "tab:mcnemar", "lrrr", "Comparison & $b$ & $c$ & $p$", body, size="\\footnotesize")

    # ---------------- 4. complete hybrid on all loops ----------------
    fh = m.get("full_hybrid", {})
    fs = m["full_set"]
    body = []
    for name, key in (("LLVM-only (HF-Static)", "HF-Static (LLVM 21)"), ("GCC autopar", "GCC autopar"), ("Polly", "Polly")):
        e = fs[key]
        body.append(f"{name} & {e['TP']} & {e['FP']} & {e['TN']} & {e['FN']} & {pct(e['precision'])} & {pct(e['recall'])} & "
                    f"{pct(e['f1'])} [{pct(e['f1_ci'][0])}, {pct(e['f1_ci'][1])}] & {e['mcc']:.3f}")
    for mm, d in fh.items():
        e, e5 = d["all"], d["all_tau50"]
        s = MODEL_SHORT[mm]
        body.append(f"Hybrid {s} ($\\tau{{=}}0.5$) & {e5['TP']} & {e5['FP']} & {e5['TN']} & {e5['FN']} & {pct(e5['precision'])} & "
                    f"{pct(e5['recall'])} & {pct(e5['f1'])} & {e5['mcc']:.3f}")
        body.append(f"\\textbf{{Hybrid {s}}} ($\\tau^*{{=}}{d['tau']:g}$) & {e['TP']} & {e['FP']} & {e['TN']} & {e['FN']} & "
                    f"{pct(e['precision'])} & {pct(e['recall'])} & {pct(e['f1'])} [{pct(e['f1_ci'][0])}, {pct(e['f1_ci'][1])}] & {e['mcc']:.3f}")
        t = TAG[mm]
        N[f"fh{t}TP"] = e["TP"]; N[f"fh{t}FP"] = e["FP"]
        N[f"fh{t}Fone"] = pct(e["f1"]) + "\\%"; N[f"fh{t}Rec"] = pct(e["recall"]) + "\\%"
        N[f"fh{t}Prec"] = pct(e["precision"]) + "\\%"
        N[f"fh{t}FoneLo"] = pct(e["f1_ci"][0]); N[f"fh{t}FoneHi"] = pct(e["f1_ci"][1])
        N[f"fh{t}OutFone"] = pct(d["outside_eval"]["f1"]) + "\\%"; N[f"fh{t}OutFP"] = d["outside_eval"]["FP"]
        N[f"fh{t}Queried"] = d["queried"]; N[f"fh{t}Missing"] = d["missing_answers"]
        N[f"fh{t}FiftyFP"] = e5["FP"]; N[f"fh{t}FiftyFone"] = pct(e5["f1"]) + "\\%"
        fp = d["false_parallel"]
        if fp:
            kinds = Counter(c for _, c in fp)
            N[f"fh{t}FPNote"] = " (" + ", ".join(f"{n}~{k.replace('_', ' ')}" for k, n in kinds.items()) + ")."
        else:
            N[f"fh{t}FPNote"] = "."
        N["fhOutN"] = d["outside_eval_n"]
        N["fhStaticOutFone"] = pct(d["outside_eval_static"]["f1"]) + "\\%"
        N["fhQueriedPct"] = pct(d["queried"] / m["benchmark"]["loops"]) + "\\%"
    if fh:
        table(os.path.join(out, "tables", "fullhybrid.tex"),
              f"All {m['benchmark']['loops']} loops of HF-LoopBench: sound compiler tools versus the complete hybrid "
              "(thresholds frozen at the values calibrated on the evaluation set's development split).",
              "tab:fullhybrid", "lrrrrrrrr", "Method & TP & FP & TN & FN & Prec. & Rec. & F1 [95\\% CI] & MCC", body, wide=True)
    cov = m.get("perf", {}).get("saving_coverage_full", {})
    for mm in fh:
        N[f"covFullH{TAG[mm]}"] = pct(cov.get(f"Hybrid {MODEL_SHORT[mm]} (tau*)", 0)) + "\\%"

    # ---------------- 5. cost of every run ----------------
    rows = [("HF-LoopBench", c) for c in m["cost"]] + [("HF-LoopBench-X", dict(c, set="all")) for c in mx.get("cost", [])]
    body = []
    for suite, c in rows:
        setname = {"eval": "eval.\\ set", "unknown": "\\textsc{Unk} (eval.)", "unknown_rest": "\\textsc{Unk} (rest)",
                   "ablation": "ablation", "ablation@2": "ablation, run 2", "all": "all"}.get(c["set"], c["set"])
        if suite == "HF-LoopBench-X" and c["variant"] == "H":
            setname = "\\textsc{Unk}"
        body.append(f"{'X' if suite.endswith('X') else 'Main'} & {MODEL_SHORT.get(c['model'], c['model'])} & {c['variant']} & {setname} & "
                    f"{c['loops']} & {c['requests']} & {num(c['prompt_tokens'])} & {num(c['completion_tokens'])} ({num(c['reasoning_tokens'])}) & "
                    f"{c['tokens_per_loop']:.0f} & {c['usd']:.4f} & {c.get('usd_with_cache', c['usd']):.4f}")
    table(os.path.join(out, "tables", "cost_all.tex"),
          "Every LLM run of this study: measured token usage and cost at Groq on-demand list prices "
          "(GPT-OSS-120B \\$0.15/\\$0.60, GPT-OSS-20B \\$0.075/\\$0.30, Qwen3.8-27B \\$0.80/\\$4.00 per million input/output tokens; "
          "``cached'' applies the 50\\% discount for cached prompt tokens of the GPT-OSS models). Output tokens include reasoning tokens (in parentheses).",
          "tab:costall", "lllrrrrrrrr",
          "Suite & Model & Prompt & Loops & & Req. & Input tok. & Output tok. (reas.) & Tok./loop & USD & USD cached".replace("Loops & &", "Set & Loops &"),
          body, size="\\scriptsize", wide=True)
    # totals over all logged requests (both suites, every successful request once)
    tot_req = tot_tok = 0
    tot_usd = 0.0
    for logf in (os.path.join(res, "llm_log.jsonl"), os.path.join(res, "ext", "llm_log.jsonl")):
        seen = set()
        for r in read_jsonl(logf):
            if not r.get("ok") or r["req_hash"] in seen:
                continue
            seen.add(r["req_hash"])
            u = r.get("usage", {})
            pin, pout = PRICES.get(r["model"], (0, 0))
            tot_req += 1
            tot_tok += u.get("prompt_tokens", 0) + u.get("completion_tokens", 0)
            tot_usd += (u.get("prompt_tokens", 0) * pin + u.get("completion_tokens", 0) * pout) / 1e6
    N.update(totRequests=num(tot_req), totTokens=num(tot_tok), totUSD=f"{tot_usd:.2f}")
    proj = m.get("cost_projection", {})
    p20 = proj.get("openai/gpt-oss-20b")
    if p20:
        N["dayCapAITwenty"] = num(int(DAILY_TOKENS / (p20["ai_only_tokens_per_1000"] / 1000)))
        N["dayCapHTwenty"] = num(int(DAILY_TOKENS / (p20["hybrid_tokens_per_1000"] / 1000)))
        fld = m["field"]
        usd_ai_loop = p20["ai_only_usd_per_1000"] / 1000
        usd_h_queried = p20["hybrid_usd_per_1000"] / 1000 / p20["fraction_queried"]
        N["fieldAIUSD"] = f"{fld['loops'] * usd_ai_loop:.3f}"
        N["fieldHUSD"] = f"{fld['verdicts'].get('UNKNOWN', 0) * usd_h_queried:.3f}"
    # cost figure
    fig = [HDR, "\\begin{figure}[htbp]", "\\centering", "\\begin{tikzpicture}", "\\begin{axis}[",
           "    ybar, bar width=0.7cm, width=11cm, height=6.2cm, ymin=0, scaled y ticks=false, yticklabel style={/pgf/number format/fixed, /pgf/number format/precision=2},",
           "    ylabel={USD per 1{,}000 analysed loops}, symbolic x coords={" +
           ",".join(MODEL_SHORT[mm] for mm in proj) + "}, xtick=data,",
           "    nodes near coords={\\pgfmathprintnumber[fixed,precision=3]\\pgfplotspointmeta}, nodes near coords align={vertical},",
           "    legend style={at={(0.5,-0.18)}, anchor=north, legend columns=1, font=\\footnotesize}, enlarge x limits=0.45,",
           "    ymajorgrids=true, grid style={dashed, gray!30}]"]
    fig.append("\\addplot[fill=pipelineMagenta!70, draw=black] coordinates {" +
               " ".join(f"({MODEL_SHORT[mm]},{d['ai_only_usd_per_1000']:.4f})" for mm, d in proj.items()) + "};")
    fig.append("\\addplot[fill=pipelineBlue!70, draw=black] coordinates {" +
               " ".join(f"({MODEL_SHORT[mm]},{d['hybrid_usd_per_1000']:.4f})" for mm, d in proj.items()) + "};")
    fig += ["\\legend{LLM-only (every loop queried), \\SystemName{} (only undecided loops queried)}", "\\end{axis}",
            "\\end{tikzpicture}",
            "\\caption{Measured token cost per 1{,}000 analysed loops at on-demand list prices (evaluation set).}",
            "\\label{fig:cost}", "\\end{figure}"]
    open(os.path.join(out, "fig_cost.tex"), "w").write("\n".join(fig) + "\n")

    # ---------------- 6. speedup figure ----------------
    bd = m.get("perf", {}).get("by_domain", {})
    if bd:
        doms = sorted(bd, key=lambda k: -bd[k])
        fig = [HDR, "\\begin{figure}[htbp]", "\\centering", "\\begin{tikzpicture}", "\\begin{axis}[",
               "    xbar, bar width=0.28cm, width=10cm, height=9cm, xmin=0,",
               f"    xlabel={{Geometric-mean speedup, {m['perf']['threads']} threads}}, symbolic y coords={{" +
               ",".join(d.replace("_", " ") for d in reversed(doms)) + "}, ytick=data, y tick label style={font=\\footnotesize},",
               "    nodes near coords={\\pgfmathprintnumber[fixed,precision=2]\\pgfplotspointmeta}, nodes near coords align={horizontal},",
               "    xmajorgrids=true, grid style={dashed, gray!30}, enlarge y limits=0.04, extra x ticks={1}, extra x tick style={grid=major, grid style={black}}]",
               "\\addplot[fill=pipelineBlue!70, draw=black] coordinates {" +
               " ".join(f"({bd[d]:.3f},{d.replace('_', ' ')})" for d in doms) + "};",
               "\\end{axis}", "\\end{tikzpicture}",
               "\\caption{Speedup of the GT-parallel kernels of HF-LoopBench per domain (Apple M1 Pro, \\Code{-O2}, minimum of three runs; kernels with wrong \\Code{-O2} output excluded).}",
               "\\label{fig:perf}", "\\end{figure}"]
        open(os.path.join(out, "fig_perf.tex"), "w").write("\n".join(fig) + "\n")

    # ---------------- 7. HF-Static v2.1 fix: diff against v2.0 records ----------------
    def load(p):
        d = {}
        for r in read_jsonl(p):
            d[(r.get("file"), r.get("line"), r.get("function"), r.get("depth"))] = r["verdict"]
        return d
    fixparts = []
    for name, a, b in (("HF-LoopBench", "results/static_v2.0/static.jsonl", "results/static.jsonl"),
                       ("HF-LoopBench-X", "results/ext/static_v2.0/static.jsonl", "results/ext/static.jsonl"),
                       ("the application corpus", "results/static_v2.0/field_static.jsonl", "results/field_static.jsonl")):
        pa, pb = os.path.join(root, a), os.path.join(root, b)
        if not (os.path.exists(pa) and os.path.exists(pb)):
            continue
        A, B = load(pa), load(pb)
        ch = Counter((A[k], B[k]) for k in A if k in B and A[k] != B[k])
        if ch:
            fixparts.append(f"on {name} " + ", ".join(f"{n}~loop{'s' if n > 1 else ''} changed from \\textsc{{{x.title()}}} to \\textsc{{{y.title()}}}"
                                                       for (x, y), n in ch.items()))
        else:
            fixparts.append(f"no verdict changed on {name}")
    fix_text = ("; ".join(fixparts) + ".") if fixparts else ""
    fix_text = fix_text[:1].upper() + fix_text[1:]

    # ---------------- 8. extension narrative ----------------
    ext_text = ""
    if mx:
        tb = {e["method"]: e for e in mx["table"]}
        def g(prefix):
            return next((e for k, e in tb.items() if k.startswith(prefix)), None)
        st, h20, a20 = tb.get("HF-Static (LLVM 21)"), g("Hybrid GPT-OSS-20B (tau*"), tb.get("AI-only GPT-OSS-20B")
        gcc = tb.get("GCC autopar")
        if st and h20 and a20:
            fv = len(mx.get("ctx_false_veto", []))
            ext_text = (f"The picture of HF-LoopBench is repeated on unseen loop shapes. HF-Static (precision {pct(st['precision'])}\\% after the fix below) "
                        f"proves only {pct(st['recall'])}\\% of the parallel loops (GCC {pct(gcc['recall'])}\\%); "
                        f"GPT-OSS-20B alone reaches F1 {pct(a20['f1'])}\\% with {a20['FP']} unsafe answers; the frozen hybrid "
                        f"reaches F1 {pct(h20['f1'])}\\% with {h20['FP']} unsafe directive{'s' if h20['FP'] != 1 else ''}. "
                        f"The call-site guard vetoes all {mx['ctx_flagged'] - fv} overlapping-call variants but also all "
                        f"{fv} disjoint-halves variants, which are legal; this is the measured price of its conservatism. ")
            pr = mx.get("level_pairs_both_right", {})
            n = mx.get("level_pairs_n", 0)
            if n:
                ext_text += (f"On the {n} level pairs (same nest, different target loop), HF-Static decides both members "
                             f"correctly in {pr.get('pred_static', 0)} cases, GPT-OSS-20B alone in "
                             f"{pr.get('pred_ai_openai/gpt-oss-20b', 0)} and the hybrid in {pr.get('pred_h_openai/gpt-oss-20b', 0)}.")
    with open(os.path.join(out, "texts_extra.tex"), "w") as f:
        f.write(HDR + "\\newcommand{\\fixText}{" + fix_text + "}\n\\newcommand{\\extText}{" + ext_text + "}\n")
    with open(os.path.join(out, "numbers_extra.tex"), "w") as f:
        f.write(HDR)
        for k in sorted(N):
            f.write(f"\\newcommand{{\\{k}}}{{{N[k]}}}\n")
    log(f"paper_extra: {len(N)} macros")


if __name__ == "__main__":
    run(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
